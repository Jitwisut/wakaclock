import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { afterEach, expect, it, vi } from 'vitest';
import { HeartbeatBufferManager } from '../src/buffer';
import { HeartbeatJournal } from '../src/heartbeatJournal';
import { prepareJournalRecovery, applyJournalRecovery } from '../src/journalRecovery';
import { scanJournal } from '../src/journalScanner';
import { validateEditorCheckpoint } from '../src/journalCheckpoint';
import { Logger } from '../src/logging';
import type { WakaclockConfigSnapshot } from '../src/types';
const roots: string[] = [];
afterEach(() => {vi.restoreAllMocks();for (const root of roots.splice(0)) fs.rmSync(root,{recursive:true,force:true});});
const config = (): WakaclockConfigSnapshot => ({cliPath:'fixture',flushIntervalMs:30000,heartbeatRateLimitMs:120000,sameFileHeartbeatMs:120000,idleMs:300000,statusBarEnabled:true,debugLogging:false,trackDebugSessions:true,trackBuildTasks:true,trackClipboardActions:true});
const make = () => new HeartbeatBufferManager(config,{sendHeartbeat:vi.fn().mockResolvedValue({stdout:'',stderr:'',exitCode:0}),acceptJournalBatch:vi.fn().mockImplementation(async (_scope,items)=>items.map((p:any)=>({heartbeat_id:p.heartbeat_id,status:'accepted'})))},new Logger(()=>false));
it('reimports the original ID once after import commits but source acknowledgement is interrupted',async()=>{
  const base=fs.mkdtempSync(path.join(os.tmpdir(),'journal-runtime-'));roots.push(base);
  const live=path.join(base,'live');const original=path.join(base,'original');fs.mkdirSync(original);
  const manager=make();manager.enableJournal(live,'scope',[original]);
  const source=make();source.enableJournal(original,'scope');
  const document={uri:{scheme:'file',fsPath:'/fixture/original.ts'}} as any;
  await source.recordClipboardCopy(document,{copiedChars:3,copiedLines:1},1000);
  await source.recordClipboardCopy(document,{copiedChars:7,copiedLines:1},2000);
  source.closeJournal();
  const directory=path.join(original,fs.readdirSync(original)[0]);const file=path.join(directory,'metadata.jsonl');
  const checkpoint=scanJournal<any>(fs.readFileSync(file),validateEditorCheckpoint).state;
  const originalId=checkpoint.states[0].heartbeatId;expect(originalId).toBeTruthy();
  fs.appendFileSync(file,'{"torn":');const plan=prepareJournalRecovery(directory,'scope',validateEditorCheckpoint);
  applyJournalRecovery(directory,plan,'scope',validateEditorCheckpoint);
  const append=HeartbeatJournal.prototype.append;
  const fault=vi.spyOn(HeartbeatJournal.prototype,'append').mockImplementation(function(this:HeartbeatJournal<any>,state:any,pending:number){
    if(this.ownsDirectory(directory)&&pending===0) throw new Error('fixture_crash_after_import');
    return append.call(this,state,pending);
  });
  await expect(manager.resumeRecoveredJournal(directory)).rejects.toThrow('fixture_crash_after_import');manager.closeJournal();fault.mockRestore();
  const restarted=make();restarted.enableJournal(live,'scope',[original]);
  const retained=fs.readdirSync(live).map(name=>scanJournal<any>(fs.readFileSync(path.join(live,name,'metadata.jsonl')),validateEditorCheckpoint).state).flatMap(state=>state.retries.flatMap((pair:any)=>pair[1]));
  expect(retained.filter((s:any)=>s.payload.heartbeat_id===originalId)).toHaveLength(1);
  expect(retained.find((s:any)=>s.payload.heartbeat_id===originalId).payload.time).toBe(2);
  expect(restarted.getJournalHealth()?.historicalIncomplete).toBe(true);
  restarted.closeJournal();
});
